export type TranslationKey = keyof typeof translations.fr;

export const defaultLocale = "fr" as const;

export const localeNames = {
  fr: "Français",
  en: "English",
} as const;

export type SupportedLocale = keyof typeof localeNames;

export function t(key: TranslationKey, values?: Record<string, string | number>, locale: SupportedLocale = defaultLocale) {
  const bundle = translations[locale] ?? translations.fr;
  let text = bundle[key as keyof typeof bundle] ?? translations.fr[key] ?? String(key);

  if (values) {
    for (const [k, v] of Object.entries(values)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }

  return text;
}

export function withTranslation(key: TranslationKey, values?: Record<string, string | number>) {
  return t(key, values, defaultLocale);
}

