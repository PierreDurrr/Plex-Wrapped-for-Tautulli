export type TranslationKey = keyof typeof translations.fr;

export const defaultLocale = "fr";

export function withTranslation(key: TranslationKey, values?: Record<string, string | number>) {
  return t(key, values, defaultLocale);
}

export function t(key: TranslationKey, values?: Record<string, string | number>, locale = defaultLocale) {
  const text = (translations as Record<string, Record<string, string>>)[locale]?.[key] ?? translations.fr[key] ?? key;
  if (!values) return text;
  return Object.entries(values).reduce((acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)), text);
}

